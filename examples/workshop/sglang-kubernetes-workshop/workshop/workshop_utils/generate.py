"""Write every manifest in this workshop from one source of truth.

    cd workshop && uv run python -m workshop_utils.generate

The committed YAML files are generated, so a change to the renderer or a
profile shows up everywhere at once, and ``tests/test_generate.py`` fails if a
committed file drifts from what the renderer produces.
"""

from __future__ import annotations

from pathlib import Path

from .k8s import WORKSHOP_ACCELERATORS
from .manifest import ServingConfig, render, to_yaml
from .profiles import profile
from .service import PARTICIPANT_SERVICE

#: The workshop root (sglang-kubernetes-workshop/); paths in headers are relative to it.
ROOT = Path(__file__).resolve().parents[2]

#: Where each manifest is written.
OUTPUTS = {
    "nvidia": ROOT / "workshop" / "manifests" / "sglang-qwen3-nvidia.yaml",
    "amd": ROOT / "admin-setup" / "demos" / "amd" / "sglang-qwen3-amd.yaml",
}

PARTICIPANT_HEADER = """\
{title}
Generated by `cd workshop && uv run python -m workshop_utils.generate`; edit workshop/workshop_utils/ instead.

The participant's service on the shared workshop cluster: name qwen3, no namespace
(kubectl uses the one in your kubeconfig), the H200 pool, no Gateway route (reach it
with kubectl port-forward). Run these from the workshop/ folder:

Apply:     kubectl apply -f {path}
Watch:     kubectl get llminferenceservice {name} -w
Logs:      kubectl logs deploy/{name}-kserve -c main -f
Chat:      kubectl port-forward svc/{name}-kserve-workload-svc 8001:8000
Remove:    kubectl delete -f {path}

To change a setting, a plain re-apply never completes (one GPU per participant): stop,
wait until the pod is gone, apply, then start again:
  kubectl annotate llminferenceservice {name} serving.kserve.io/stop=true --overwrite
  kubectl apply -f {path}
  kubectl annotate llminferenceservice {name} serving.kserve.io/stop-
"""

ADMIN_HEADER = """\
{title}
Generated by `cd workshop && uv run python -m workshop_utils.generate`; edit workshop/workshop_utils/ instead.

Apply:   kubectl apply -f {path}
Watch:   kubectl get llminferenceservice -n {ns} -w
Logs:    kubectl logs -n {ns} deploy/{name}-kserve -c main -f
Remove:  kubectl delete -f {path}

What differs between the NVIDIA and AMD files: the container image, the GPU
resource name in `resources`, the `crusoe.ai/accelerator` node label, and one
environment variable. Everything else is identical.
"""


def participant_manifest() -> dict:
    """The participant's LLMInferenceService: name ``qwen3``, the H200 pool, no gateway route."""
    prof = profile("nvidia", accelerator=WORKSHOP_ACCELERATORS["nvidia"])
    doc = render(prof, ServingConfig(name=PARTICIPANT_SERVICE, gateway=False))
    del doc["metadata"]["namespace"]  # kubectl applies it to the namespace of the current context
    return doc


def manifests() -> dict[Path, str]:
    """Return ``{path: yaml}`` for every generated file."""
    nvidia = OUTPUTS["nvidia"]
    amd_path = OUTPUTS["amd"]
    amd_cfg = ServingConfig(name="qwen3-amd")
    amd = profile("amd")
    return {
        nvidia: to_yaml(
            participant_manifest(),
            PARTICIPANT_HEADER.format(
                title="SGLang serving Qwen3-8B on one NVIDIA H200 GPU through KServe (participant baseline).",
                path=nvidia.relative_to(ROOT / "workshop"),
                name=PARTICIPANT_SERVICE,
            ),
        ),
        amd_path: to_yaml(
            render(amd, amd_cfg),
            ADMIN_HEADER.format(
                title=f"SGLang serving Qwen3-8B on one {amd.label} GPU through KServe (baseline).",
                path=amd_path.relative_to(ROOT),
                ns=amd_cfg.namespace,
                name=amd_cfg.name,
            ),
        ),
    }


def main() -> None:
    for path, text in manifests().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
